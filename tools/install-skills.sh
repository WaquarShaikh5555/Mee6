#!/usr/bin/env bash
#
# install-skills.sh - reproduce the skills/ directory from pinned upstream repositories.
#
# Usage:
#   tools/install-skills.sh            install / refresh every skill in the manifest
#   tools/install-skills.sh --prune    also delete skills/ dirs that are not in the manifest
#   tools/install-skills.sh --offline  reuse the local clone cache, never touch the network
#
# Safety:
#   * Only `git clone` / `git fetch` and `cp` are used. No script from any upstream
#     repository is ever executed.
#   * Clones are shallow and land in the git-ignored cache dir, not in the repo.
#   * The target directory for each skill is removed and recreated, so the result is
#     always exactly what the manifest describes.
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MANIFEST="$ROOT/tools/skills.manifest.tsv"
DEST="$ROOT/skills"
CACHE="${SKILLS_CACHE_DIR:-$ROOT/.cache/skills-src}"
LOCK="$ROOT/tools/skills.lock"

PRUNE=0
OFFLINE=0
for arg in "$@"; do
  case "$arg" in
    --prune)   PRUNE=1 ;;
    --offline) OFFLINE=1 ;;
    -h|--help) sed -n '2,20p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

declare -A REPOS=(
  [anthropics]="https://github.com/anthropics/skills.git"
  [vercel]="https://github.com/vercel-labs/agent-skills.git"
  [addy]="https://github.com/addyosmani/agent-skills.git"
  [expo]="https://github.com/expo/skills.git"
  [flutter]="https://github.com/flutter/agent-plugins.git"
  [dart]="https://github.com/dart-lang/skills.git"
  [chrisbanes]="https://github.com/chrisbanes/skills.git"
  [android-awesome]="https://github.com/new-silvermoon/awesome-android-agent-skills.git"
  [partme-kotlin]="https://github.com/full-stack-skills/kotlin-skills.git"
  [partme-swift]="https://github.com/full-stack-skills/swift-skills.git"
  [twostraws]="https://github.com/twostraws/SwiftUI-Agent-Skill.git"
  [apple]="https://github.com/rshankras/claude-code-apple-skills.git"
  [ts]="https://github.com/mkosir/typescript-style-guide.git"
)

command -v git >/dev/null || { echo "git is required" >&2; exit 1; }

mkdir -p "$CACHE" "$DEST"

# ---------------------------------------------------------------- fetch sources
echo "==> fetching upstream repositories into $CACHE"
for key in "${!REPOS[@]}"; do
  url="${REPOS[$key]}"
  dir="$CACHE/$key"
  if [[ -d "$dir/.git" ]]; then
    if [[ $OFFLINE -eq 0 ]]; then
      git -C "$dir" fetch --depth 1 --quiet origin HEAD 2>/dev/null || \
        echo "    warn: could not refresh $key, using cached copy" >&2
      git -C "$dir" reset --hard --quiet FETCH_HEAD 2>/dev/null || true
    fi
  else
    if [[ $OFFLINE -eq 1 ]]; then
      echo "    error: $key is not cached and --offline was requested" >&2; exit 1
    fi
    git clone --depth 1 --quiet "$url" "$dir" || { echo "    error: clone failed: $url" >&2; exit 1; }
  fi
done

# ------------------------------------------------------------------- copy skills
installed=0
failures=0
: > "$LOCK.tmp"

while IFS=$'\t' read -r category name repo src upstream; do
  [[ -z "${category:-}" || "$category" == \#* ]] && continue
  src_repo="$CACHE/$repo"
  from="$src_repo/$src"

  if [[ ! -f "$from/SKILL.md" ]]; then
    echo "FAIL  $name  (missing $src/SKILL.md in $repo)" >&2
    failures=$((failures + 1))
    continue
  fi

  rm -rf "$DEST/$name"
  mkdir -p "$DEST/$name"
  # Copy the skill directory verbatim, minus VCS and OS cruft.
  tar -C "$from" --exclude=.git --exclude=node_modules --exclude=.DS_Store -cf - . \
    | tar -C "$DEST/$name" -xf -

  # Keep frontmatter name in sync with the directory name (Agent Skills requirement).
  current="$(awk 'NR==1&&/^---/{f=1;next} f&&/^name:/{sub(/^name:[[:space:]]*/,"");gsub(/["'\'']/,"");print;exit}' "$DEST/$name/SKILL.md")"
  target="${upstream:-$name}"
  if [[ -n "$current" && "$current" != "$name" ]]; then
    if [[ "$current" == "$target" ]]; then
      awk -v new="$name" '
        BEGIN{done=0}
        { if (!done && $0 ~ /^name:[[:space:]]*/) { print "name: " new; done=1 } else print }
      ' "$DEST/$name/SKILL.md" > "$DEST/$name/SKILL.md.tmp"
      mv "$DEST/$name/SKILL.md.tmp" "$DEST/$name/SKILL.md"
    else
      echo "FAIL  $name  (upstream name '$current' does not match manifest '$target')" >&2
      failures=$((failures + 1))
      continue
    fi
  fi

  commit="$(git -C "$src_repo" rev-parse HEAD)"
  printf '%s\t%s\t%s\t%s\t%s\n' "$name" "$repo" "${REPOS[$repo]}" "$commit" "$src" >> "$LOCK.tmp"
  printf '  ok  %-42s %-28s %s\n' "$name" "$category" "$(echo "$commit" | cut -c1-10)"
  installed=$((installed + 1))
done < "$MANIFEST"

if [[ $failures -gt 0 ]]; then
  rm -f "$LOCK.tmp"
  echo "==> aborted: $failures skill(s) failed; skills/ is incomplete" >&2
  exit 1
fi

{
  echo "# Generated by tools/install-skills.sh - do not edit by hand."
  echo "# name	repo-key	repo-url	commit	path-in-repo"
  sort "$LOCK.tmp"
} > "$LOCK"
rm -f "$LOCK.tmp"

# --------------------------------------------------------------- optional prune
if [[ $PRUNE -eq 1 ]]; then
  while IFS= read -r existing; do
    base="$(basename "$existing")"
    if ! cut -f2 "$MANIFEST" | grep -qx -- "$base"; then
      echo "  prune $base"
      rm -rf "$existing"
    fi
  done < <(find "$DEST" -mindepth 1 -maxdepth 1 -type d | sort)
fi

# ------------------------------------------------------------- agent discovery
# Claude Code and compatible agents discover project skills in .claude/skills.
if [[ ! -e "$ROOT/.claude/skills" ]]; then
  mkdir -p "$ROOT/.claude"
  ln -sfn ../skills "$ROOT/.claude/skills"
  echo "==> linked .claude/skills -> ../skills"
fi

echo "==> installed $installed skill(s) into $DEST"
echo "==> lockfile: $LOCK"
